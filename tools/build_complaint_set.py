#!/usr/bin/env python3
"""Merge the triage verdicts into the confirmed-complaint set.

Reads notes/taxonomy/triage/*.tsv (id, verdict, one-line note) and joins them
against corpus/pushbacks/human-turns.jsonl. Writes the COMPLAINT-verdict turns
to corpus/pushbacks/COMPLAINTS.md — the input the taxonomy pass classifies —
and reports any turn the triage missed, since a gap there is silent data loss.
"""

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRIAGE = ROOT / "notes" / "taxonomy" / "triage"
TURNS = ROOT / "corpus" / "pushbacks" / "human-turns.jsonl"
OUT = ROOT / "corpus" / "pushbacks" / "COMPLAINTS.md"

VALID = {"COMPLAINT", "CHANGE", "NEITHER"}


def main():
    verdicts = {}
    malformed = []
    for tsv in sorted(TRIAGE.glob("*.tsv")):
        for line in tsv.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            cols = line.split("\t")
            if len(cols) < 2 or cols[1].strip() not in VALID:
                malformed.append((tsv.name, line[:60]))
                continue
            note = cols[2].strip() if len(cols) > 2 else ""
            verdicts[cols[0].strip()] = (cols[1].strip(), "" if note == "-" else note)

    turns = {}
    for line in TURNS.open(encoding="utf-8"):
        r = json.loads(line)
        turns[r["id"]] = r

    missing = sorted(set(turns) - set(verdicts))
    unknown = sorted(set(verdicts) - set(turns))
    counts = Counter(v for v, _ in verdicts.values())

    # Claude Code re-appends earlier turns after a compaction or resume, so the
    # same turn can appear twice under different indices. Keep the first, mark
    # the rest -- renumbering would break every ID the taxonomies already cite.
    canonical = {}
    duplicate_of = {}
    for i in sorted(turns):
        key = (turns[i]["session"], turns[i]["human"])
        if key in canonical:
            duplicate_of[i] = canonical[key]
        else:
            canonical[key] = i

    picked = [turns[i] for i in sorted(turns)
              if verdicts.get(i, ("", ""))[0] == "COMPLAINT" and i not in duplicate_of]
    dup_complaints = [i for i in sorted(duplicate_of)
                      if verdicts.get(i, ("", ""))[0] == "COMPLAINT"]

    md = [
        "# Confirmed complaints",
        "",
        "Turns triaged as objections to Claude's conduct, drawn from the 755 turns",
        "[HUMAN] typed across the archived sessions. Generated by",
        "`tools/build_complaint_set.py` from `notes/taxonomy/triage/`.",
        "",
        f"**{len(picked)} distinct complaints** out of {len(turns)} human turns "
        f"({counts['CHANGE']} redirections, {counts['NEITHER']} neither).",
        "",
        f"{len(dup_complaints)} further complaint records are verbatim duplicates and are"
        " excluded: " + (", ".join(f"{i}={duplicate_of[i]}" for i in dup_complaints) or "none")
        + ". Claude Code re-appends earlier turns after a compaction, so the same turn"
        " lands twice. IDs are never renumbered.",
        "",
        "Each entry carries the triager's one-line reading of what Claude did.",
        "That line is a hint, not a verdict — read the turn.",
        "",
        "---",
        "",
    ]
    for r in picked:
        note = verdicts[r["id"]][1]
        md += [
            f"## {r['id']} — `{r['session']}` turn {r['turn']} — {r['ts'][:16]}",
            "",
            f"*Triage read:* {note or '(none given)'}",
            "",
            "**Claude, immediately before:**",
            "",
            "> " + (r["assistant_before"] or "*(session opening — no prior turn)*").replace("\n", "\n> "),
            "",
            "**[HUMAN]:**",
            "",
            "> " + r["human"].replace("\n", "\n> "),
            "",
            "---",
            "",
        ]
    OUT.write_text("\n".join(md), encoding="utf-8")

    print(f"{len(picked)} distinct complaints / {len(turns)} human turns "
          f"({len(dup_complaints)} duplicate complaint records excluded)")
    print("  " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if missing:
        print(f"UNTRIAGED ({len(missing)}): {', '.join(missing[:12])}"
              + (" …" if len(missing) > 12 else ""))
    if unknown:
        print(f"UNKNOWN IDS ({len(unknown)}): {', '.join(unknown[:12])}")
    for name, line in malformed:
        print(f"MALFORMED {name}: {line}")


if __name__ == "__main__":
    main()
