#!/usr/bin/env python3
"""Regenerate corpus/INDEX.md from the archived raw transcripts."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "corpus" / "raw"


def summarise(path):
    title = mode = None
    stamps, human, assistant = [], 0, 0
    for line in path.open(encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if r.get("timestamp"):
            stamps.append(r["timestamp"])
        t = r.get("type")
        if t == "ai-title":
            title = r.get("aiTitle")
        elif t == "permission-mode":
            mode = r.get("permissionMode")
        elif t == "assistant":
            assistant += 1
        elif t == "user":
            c = r.get("message", {}).get("content")
            parts = [{"type": "text"}] if isinstance(c, str) else (c or [])
            if any(b.get("type") != "tool_result" for b in parts):
                human += 1
    return {
        "title": title,
        "mode": mode,
        "start": min(stamps) if stamps else "",
        "end": max(stamps) if stamps else "",
        "human": human,
        "assistant": assistant,
        "bytes": path.stat().st_size,
    }


def main():
    sessions = sorted(p for p in RAW.glob("*/*.jsonl"))
    lines = [
        "# Corpus index",
        "",
        "Auto-generated by `tools/build_corpus_index.py`. Top-level sessions only;",
        "subagent transcripts live beside their parent under `corpus/raw/*/<id>/subagents/`.",
        "",
        "| Session | Project | Human turns | Assistant turns | Start | Raw |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    total = 0
    for p in sessions:
        s = summarise(p)
        total += s["bytes"]
        link = f"corpus/rendered/{p.parent.name}/{p.stem}.md"
        label = s["title"] or p.stem[:8]
        lines.append(
            f"| [{label}]({link}) | `{p.parent.name}` | {s['human']} | {s['assistant']} "
            f"| {s['start'][:16]} | {s['bytes'] / 1048576:.1f} MB |"
        )
    subagents = len(list(RAW.glob("*/*/subagents/**/*.jsonl")))
    lines += [
        "",
        f"**{len(sessions)} sessions**, {total / 1048576:.0f} MB raw, "
        f"plus {subagents} subagent transcripts.",
        "",
    ]
    (ROOT / "corpus" / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"indexed {len(sessions)} sessions, {subagents} subagent transcripts")


if __name__ == "__main__":
    main()
