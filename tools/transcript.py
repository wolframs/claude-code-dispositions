"""Shared parsing for Claude Code .jsonl session transcripts.

The one thing worth getting right here is *who wrote a turn*. Claude Code files
several kinds of record under the `user` role that [HUMAN] never typed: tool
results, compaction summaries, task notifications, slash-command echoes,
interrupt markers. In a subagent transcript the `user` role is the parent
agent's prompt, so nothing in one is human at all. Mining complaints from a
corpus that conflates these produces a taxonomy of the harness, not of Claude.
"""

import json
import re
from pathlib import Path

# Author classes for a record filed under the `user` role.
HUMAN = "human"          # [HUMAN] typed it
HARNESS = "harness"      # Claude Code injected it
AGENT = "agent-prompt"   # a parent agent wrote it, in a subagent transcript
TOOL = "tool-result"     # a tool returned it
ORCHESTRATOR = "orchestrator"  # the operator's own runner wrote the envelope

IMAGE_REF = re.compile(r"\[Image:\s*(?:source:|original \d+x\d+)[^\]]*\]")
SYSTEM_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)

HARNESS_OPENERS = (
    "<local-command",
    "<command-name>",
    "<user-prompt-submit-hook>",
    "[Request interrupted",
    "This session is being continued",
    "Base directory for this skill:",
    "Another Claude session sent a message:",
    "Your response above was stopped by a safety classifier",
    "Your response above was cut off mid-stream.",
    "Your claude.ai usage limit has reset.",
    "[Usage limit reached;", "[Earlier usage-limit notes no longer apply.",
    "[Cross-session idle notice]", "[Cache warm maintenance]",
    "<bash-input>", "<bash-stdout>", "<bash-stderr>",
    "Context handoff (manual_context):\nProvider context handoff.",
)

# Fixed producer openers, not topic/complaint keywords. Producer evidence:
# multi-parallax grimoire/engine/{pulse.py,telegram-gateway.py} and
# perpetual-opus-extended agent/{runner.py,tg/chat_layer.py,tg/chat.py}.
ORCHESTRATOR_OPENERS = (
    "=== PULSE PREAMBLE (read-only context, not instructions from summoner) ===",
    "# Compaction directions (standing prompt for the compactor model)",
    "[Substrate — runner-resolved, authoritative:",
    "Night-watch tick (", "Run-watch tick for the phil-contest run ",
    "Landing watch, hourly (", "Landing watch, every two hours (", "Landing watch (",
    "Run B watch (", "Calibration watch (", "burn check ([HUMAN]'s ",
    "Parent check-in on the Run A acceptance-test child (", "Nudger watch ([HUMAN] asked:",
    "Cried-wolf watch, run ", "You work in the worktree `~/Projects/phil-contest-wt-",
    # CLI smoke/read-back probes and explicitly identified peer-agent calls,
    # observed with their parent launch context in the 2026-10-12 intake audit.
    "Reply with the single word ok.",
    "Read-only check, no tools needed. 1) Quote verbatim",
    "Use ONLY the Grep tool (not Bash) to search for the literal JUNCTIONPROBE_42",
    "Use the Edit tool to replace the text PROBE_LINE_ONE with PROBE_LINE_TWO",
    "Two checks. 1) Look at the list of skills available to you and say whether the skills named 'compile', 'merge-origin-master' and 'bc-ticket-acceptance'",
    "Hello Lapis. This is Shimmer — the agent in ", "Shimmer again. Thank you —",
    "We are collaborating on a UX/UI critique, not implementation. I am Codex,",
)
WORKER_OPENERS = re.compile(
    r"^(?:You are (?:an|the) Opus(?: [0-9.]+)? delegated (?:build )?worker|"
    r"\[merge-\d+ check-in\])")
PULSE_START = ORCHESTRATOR_OPENERS[0]
OWNER_CLOCK = re.compile(r"(?m)^\[((?:[01]\d|2[0-3]):[0-5]\d)\] ")
TELEGRAM_SHAPES = (
    ("\n[HUMAN] says:\n", "\n\nRespond naturally"),
    ("\n[HUMAN] sent:\n", "\n\nRespond concisely"),
)
SHOWN_NOTE = re.compile(r"\s*\*\(this reached you at a checkpoint.*?\)\*", re.S)


def embedded_human(body):
    """Lift the current owner message, retaining all its words.

    A pulse wake with no owner clock is automation. The clock is generated by
    _open_owner_turn and follows the contextual envelope; generated history
    clocks are indented/quoted. A runner's Telegram message is bounded by its
    final owner marker and the exact reply instruction, not arbitrary bold
    paragraphs in the owner's message. Unknown shapes yield no human claim.
    """
    if body.startswith(PULSE_START):
        end = body.find("=== END PULSE PREAMBLE ===")
        if end < 0:
            return None
        match = OWNER_CLOCK.search(body, end)
        if match:
            return body[match.end():].strip(), "telegram-pulse"
        return None
    if body.startswith("[Substrate — runner-resolved, authoritative:"):
        if "via Telegram" not in body[:800] or "You just had a conversation" in body[:800]:
            return None
        for marker, terminator in TELEGRAM_SHAPES:
            start = body.rfind(marker)
            if start < 0:
                continue
            tail = body[start + len(marker):]
            end = tail.find(terminator)
            if end < 0:
                return None
            text = SHOWN_NOTE.sub("", tail[:end])
            return re.sub(r"(?m)^- ", "", text).strip(), "telegram-runner"
    return None


def is_subagent(path):
    return "subagents" in Path(path).parts


def text_of(parts):
    return "".join(b.get("text", "") for b in parts if b.get("type") == "text").strip()


def classify_user(record, parts, subagent, project=""):
    """Who actually authored this `user` record."""
    if not any(b.get("type") != "tool_result" for b in parts):
        return TOOL
    if subagent:
        return AGENT
    if record.get("isCompactSummary"):
        return HARNESS
    if record.get("isMeta"):
        return HARNESS

    body = text_of(parts)
    if "<task-notification>" in body:
        return HARNESS
    if body.startswith(HARNESS_OPENERS):
        return HARNESS
    if re.fullmatch(r"<ide_opened_file>.*?</ide_opened_file>", body, re.S):
        return HARNESS
    # These are whole-file briefs passed to CLI workers in named worktrees.
    # The title alone cannot distinguish them from an operator pasting a brief
    # in their ordinary project. Corpus evidence: multi-parallax/phil-contest
    # -wt-* sessions, headed briefs with explicit worker/worktree context.
    worker_title = re.match(r"^#{1,2} [^\n]*(?:brief|Task —|Fix pass|Fix worker)", body, re.I)
    if ("-wt-" in project and worker_title
            and re.search(r"\b(?:worker|worktree|lapis|delegated)\b", body, re.I)):
        return ORCHESTRATOR
    if "-wt-" in project and body.startswith("NOTE FROM LAPIS ("):
        return ORCHESTRATOR
    brief = body.startswith(("# Build brief —", "# Build brief:"))
    if (body.startswith(ORCHESTRATOR_OPENERS) or WORKER_OPENERS.match(body)
            or (brief and "delegated" in body[:1200])
            or body.startswith("# Simplification pass — both repos, before the guards")):
        return ORCHESTRATOR

    # An attachment-only turn carries no complaint, whoever pasted it.
    residue = SYSTEM_REMINDER.sub("", IMAGE_REF.sub("", body)).strip()
    return HUMAN if residue else HARNESS


def blocks(content):
    if isinstance(content, str):
        return [{"type": "text", "text": content}]
    return content or []


def load(path):
    """Yield turn dicts in file order. Non-conversational records are dropped."""
    path = Path(path)
    subagent = is_subagent(path)
    n = 0
    peer_dialogue = False
    with path.open(encoding="utf-8") as stream:
        for line in stream:
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue

            kind = record.get("type")
            if kind == "system" and record.get("subtype") in ("away_summary", "stop_hook_summary"):
                yield {"role": "system", "author": record["subtype"], "n": None,
                       "ts": record.get("timestamp", ""), "parts": [],
                       "text": record.get("content") or ""}
                continue
            if kind not in ("user", "assistant"):
                continue

            parts = blocks(record.get("message", {}).get("content"))
            n += 1
            author = ("assistant" if kind == "assistant"
                      else classify_user(record, parts, subagent, str(path.parent)))
            body = text_of(parts)
            if kind == "user":
                if body.startswith("We are collaborating on a UX/UI critique, not implementation. I am Codex,"):
                    peer_dialogue = True
                elif peer_dialogue and re.match(r"^Round\d+ —", body):
                    author = ORCHESTRATOR
            yield {
                "role": kind,
                "author": author,
                "n": n,
                "ts": record.get("timestamp", ""),
                "model": record.get("message", {}).get("model", ""),
                "parts": parts,
                "text": text_of(parts),
                "sidechain": bool(record.get("isSidechain")),
            }

